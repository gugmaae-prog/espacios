import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';

const root=new URL('../',import.meta.url);
const manifest=JSON.parse(await fs.readFile(new URL('data/recovery/psr-public-d1-export-20261102.manifest.json',root)));
const compressed=await fs.readFile(new URL('data/recovery/psr-public-d1-export-20261102.json.gz',root));
const raw=gunzipSync(compressed);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
if(compressed.length!==manifest.compressedBytes||sha(compressed)!==manifest.compressedSha256||raw.length!==manifest.rawBytes||sha(raw)!==manifest.rawSha256)throw Error('Reviewed D1 public export checksum mismatch');
const data=JSON.parse(raw);
if(data.projects?.length!==manifest.rows||data.registry?.total!==manifest.registry.total||data.registry?.revision!==manifest.registry.revision||data.registry?.contentHash!==manifest.registry.contentHash)throw Error('Reviewed D1 public export population mismatch');
const emirates={},developers=new Set(),propertyTypes=new Set();
for(const project of data.projects){
  if(project.emirate)emirates[project.emirate]=(emirates[project.emirate]||0)+1;
  if(project.developer)developers.add(project.developer);
  for(const type of Array.isArray(project.propertyTypes)?project.propertyTypes:[])if(typeof type==='string'&&type.trim())propertyTypes.add(type.trim());
}
const filters={emirates,developers:[...developers].sort((a,b)=>a.localeCompare(b)),propertyTypes:[...propertyTypes].sort((a,b)=>a.localeCompare(b))};
const payload={sourceRawSha256:manifest.rawSha256,registry:manifest.registry,filters};
const moduleText='// Generated by scripts/build-data-hub-filters.mjs from the checksum-verified public D1 export.\nexport const PSR_PUBLIC_FILTERS='+JSON.stringify(payload)+';\n';
const destination=new URL('src/data-hub/psr-public-filters.mjs',root);
if(process.argv.includes('--check')){
  if(await fs.readFile(destination,'utf8')!==moduleText)throw Error('Data Hub filter metadata is stale');
}else await fs.writeFile(destination,moduleText);
console.log(JSON.stringify({passed:true,rows:data.projects.length,developers:developers.size,propertyTypes:propertyTypes.size,sourceRawSha256:manifest.rawSha256,check:process.argv.includes('--check')}));
