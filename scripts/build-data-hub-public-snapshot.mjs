import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';

const root=new URL('../',import.meta.url);
const manifest=JSON.parse(await fs.readFile(new URL('data/recovery/psr-public-d1-export-20261102.manifest.json',root)));
const compressed=await fs.readFile(new URL('data/recovery/psr-public-d1-export-20261102.json.gz',root));
const raw=gunzipSync(compressed);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
if(compressed.length!==manifest.compressedBytes||sha(compressed)!==manifest.compressedSha256||raw.length!==manifest.rawBytes||sha(raw)!==manifest.rawSha256)throw Error('Reviewed D1 public export checksum mismatch');
const parsed=JSON.parse(raw);
if(parsed.projects?.length!==manifest.rows||new Set(parsed.projects.map(row=>row.slug)).size!==manifest.uniqueSlugs||parsed.registry?.total!==manifest.registry.total)throw Error('Reviewed D1 public export population mismatch');
const moduleText=`// Generated by scripts/build-data-hub-public-snapshot.mjs from the reviewed public D1 export.\nexport const PSR_PUBLIC_SNAPSHOT=${JSON.stringify({...manifest,base64:compressed.toString('base64')})};\n`;
const destination=new URL('src/data-hub/psr-public-snapshot.mjs',root);
if(process.argv.includes('--check')){
 if(await fs.readFile(destination,'utf8')!==moduleText)throw Error('Data Hub public snapshot module is stale');
}else await fs.writeFile(destination,moduleText);
console.log(JSON.stringify({passed:true,rows:manifest.rows,sha256:manifest.rawSha256,check:process.argv.includes('--check')}));
